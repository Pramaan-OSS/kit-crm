// Writes app/routes.generated.ts (the app's route list and navigation) from every
// app/<feature>/pramaan.feature.json, so no two features edit one shared file (#716). The output is
// never committed; `pnpm generate`, `pnpm build` and `pramaan check` write it, the same bytes for
// the same manifests. Usage: node scripts/generate-routes.mjs [dir]. Exits 1 and names each problem.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const OUTPUT = "app/routes.generated.ts";
const MANIFEST = "pramaan.feature.json";
const ROUTE = /^\/(?:[a-z0-9][a-z0-9-]*(?:\/[a-z0-9][a-z0-9-]*)*)?$/u;
const MAX_LABEL = 40;
const byName = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function manifests(root, dir) {
  let entries = [];
  try {
    entries = readdirSync(path.join(root, dir), { withFileTypes: true });
  } catch {
    return [];
  }
  return entries
    .sort((a, b) => byName(a.name, b.name))
    .flatMap((entry) => {
      if (entry.name.startsWith(".") || entry.name === "node_modules") return [];
      const file = `${dir}/${entry.name}`;
      if (entry.isDirectory()) return manifests(root, file);
      return entry.isFile() && entry.name === MANIFEST ? [file] : [];
    });
}

const root = path.resolve(process.argv[2] ?? ".");
const problems = [];
const routes = new Map();
const nav = new Map();
for (const file of manifests(root, "app")) {
  const say = (problem) => problems.push(`${file}: ${problem}`);
  if (file === `app/${MANIFEST}`) {
    say("put it beside the feature's page, in app/<feature>/");
    continue;
  }
  let data;
  try {
    data = JSON.parse(readFileSync(path.join(root, file), "utf8"));
  } catch (error) {
    say(`not valid JSON (${error.message})`);
    continue;
  }
  if (data === null || typeof data !== "object" || Array.isArray(data)) {
    say('must be an object: {"routes": ["/x"], "nav": [{"label": "X", "href": "/x"}]}');
    continue;
  }
  for (const key of Object.keys(data))
    if (key !== "routes" && key !== "nav") say(`unknown key "${key}"`);
  const declared = data.routes ?? [];
  const entries = data.nav ?? [];
  if (!Array.isArray(declared) || !Array.isArray(entries)) {
    say('"routes" and "nav" are lists');
    continue;
  }
  for (const route of declared) {
    if (typeof route !== "string" || !ROUTE.test(route)) {
      say(`route ${JSON.stringify(route)} is not a page path like "/budget" (a-z, 0-9, "-")`);
    } else if (routes.has(route)) {
      say(`route ${route} is already declared by ${routes.get(route)}`);
    } else routes.set(route, file);
  }
  for (const entry of entries) {
    const { label, href } = entry ?? {};
    if (
      typeof label !== "string" ||
      label.trim() === "" ||
      label.length > MAX_LABEL ||
      /\p{Cc}/u.test(label)
    ) {
      say(`nav label ${JSON.stringify(label)} must be plain text of 1 to ${MAX_LABEL} characters`);
    } else if (typeof href !== "string" || !ROUTE.test(href)) {
      say(`nav href ${JSON.stringify(href)} is not a page path like "/budget"`);
    } else if (nav.has(href)) {
      say(`nav entry ${href} is already declared by ${nav.get(href).file}`);
    } else nav.set(href, { label, href, file });
  }
}
for (const entry of nav.values()) {
  if (entry.href !== "/" && !routes.has(entry.href)) {
    problems.push(`${entry.file}: nav href ${entry.href} is a route no manifest declares`);
  }
}
if (problems.length > 0) {
  console.error("generate-routes: fix these pramaan.feature.json files:");
  for (const problem of problems) console.error(`  ${problem}`);
  process.exit(1);
}

const list = [...nav.values()]
  .sort((a, b) => byName(a.href, b.href))
  .map(({ label, href }) => ({ label, href }));
const text = [
  "// Generated by scripts/generate-routes.mjs from every app/<feature>/pramaan.feature.json. Do not edit:",
  "// declare a page or a nav entry in the feature's own pramaan.feature.json.",
  "export type NavEntry = { readonly label: string; readonly href: string };",
  `export const routes: readonly string[] = ${JSON.stringify([...routes.keys()].sort(byName))};`,
  `export const nav: readonly NavEntry[] = ${JSON.stringify(list)};`,
  "",
].join("\n");
const target = path.join(root, OUTPUT);
if (!existsSync(target) || readFileSync(target, "utf8") !== text) writeFileSync(target, text);
console.log(`generate-routes: ${routes.size} routes, ${list.length} nav entries`);
